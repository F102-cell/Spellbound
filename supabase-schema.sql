create or replace function public.prevent_blocked_players_sharing_match()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
    perform 1
    from public.online_matches
    where id = new.match_id
        and status = 'waiting'
    for update;
    if not found then
        raise exception 'This match is no longer accepting players.'
            using errcode = '23514';
    end if;
    if (
        select count(*)
        from public.online_match_players
        where match_id = new.match_id
    ) >= (
        select max_players
        from public.online_matches
        where id = new.match_id
    ) then
        raise exception 'This match is full.'
            using errcode = '23514';
    end if;

    if exists (
        select 1
        from public.online_matches as party
        where party.id = new.match_id
            and party.is_party
            and party.host_id <> new.user_id
    ) and not exists (
        select 1
        from public.online_party_invites as invitation
        where invitation.match_id = new.match_id
            and invitation.invitee_id = new.user_id
            and invitation.status = 'accepted'
    ) then
        raise exception 'An accepted party invitation is required to join.'
            using errcode = '23514';
    end if;

    if exists (
        select 1
        from public.online_match_players as participant
        join public.player_blocks as player_block
            on (player_block.blocker_id = new.user_id and player_block.blocked_id = participant.user_id)
            or (player_block.blocked_id = new.user_id and player_block.blocker_id = participant.user_id)
        where participant.match_id = new.match_id
    ) then
        raise exception 'Blocked players cannot join the same match.'
            using errcode = '23514';
    end if;
    return new;
end;
$$;

drop trigger if exists prevent_blocked_players_sharing_match
    on public.online_match_players;
create trigger prevent_blocked_players_sharing_match
    before insert on public.online_match_players
    for each row execute function public.prevent_blocked_players_sharing_match();

create or replace function public.accept_online_party_invite(invite_id bigint)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
    accepted_invite public.online_party_invites%rowtype;
    current_user_id uuid := auth.uid();
begin
    if current_user_id is null then
        raise exception 'Sign in to accept a party invite.';
    end if;

    select * into accepted_invite
    from public.online_party_invites
    where id = invite_id
        and invitee_id = current_user_id
        and status = 'pending'
    for update;

    if not found then
        raise exception 'Party invite is no longer available.';
    end if;
    if not exists (
        select 1 from public.online_matches
        where id = accepted_invite.match_id
            and is_party
            and status = 'waiting'
    ) then
        raise exception 'This party is no longer available.';
    end if;
    if exists (
        select 1 from public.player_blocks
        where (blocker_id = current_user_id and blocked_id = accepted_invite.inviter_id)
            or (blocked_id = current_user_id and blocker_id = accepted_invite.inviter_id)
    ) then
        raise exception 'Blocked players cannot join the same party.';
    end if;

    update public.online_party_invites
    set status = 'accepted'
    where id = accepted_invite.id;

    insert into public.online_match_players (match_id, user_id, team)
    select accepted_invite.match_id,
        current_user_id,
        case when online_match.mode = 'co-op' then 1 else null end
    from public.online_matches as online_match
    where online_match.id = accepted_invite.match_id
    on conflict (match_id, user_id) do nothing;

    return accepted_invite.match_id;
end;
$$;

revoke all on function public.accept_online_party_invite(bigint) from public, anon;
grant execute on function public.accept_online_party_invite(bigint) to authenticated;

