declare
    current_primary_key record;
begin
    select constraint_row.conname, pg_get_constraintdef(constraint_row.oid) as definition
    into current_primary_key
    from pg_constraint as constraint_row
    where constraint_row.conrelid = 'public.normal_mode_leaderboard'::regclass
        and constraint_row.contype = 'p';

    if current_primary_key.conname is null then
        alter table public.normal_mode_leaderboard
            add constraint normal_mode_leaderboard_pkey primary key (user_id, difficulty);
    elsif current_primary_key.definition <> 'PRIMARY KEY (user_id, difficulty)' then
        execute format(
            'alter table public.normal_mode_leaderboard drop constraint %I',
            current_primary_key.conname
        );
        alter table public.normal_mode_leaderboard
            add constraint normal_mode_leaderboard_pkey primary key (user_id, difficulty);
    end if;
end;
$$;

