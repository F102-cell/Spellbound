create or replace function public.require_all_online_players_ready()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
    player_count integer;
    ready_count integer;
begin
    if new.status = 'in_progress' and old.status is distinct from 'in_progress' then
        if old.status <> 'waiting' then
            raise exception 'Only a waiting match can be started.'
                using errcode = '23514';
        end if;

        perform 1
        from public.online_match_players
        where match_id = new.id
        for update;

        select count(*), count(*) filter (where is_ready)
        into player_count, ready_count
        from public.online_match_players
        where match_id = new.id;

        if player_count < 2 or ready_count <> player_count then
            raise exception 'Every player must be ready before the match can start.'
                using errcode = '23514';
        end if;
    end if;
    return new;
end;
$$;

drop trigger if exists require_all_online_players_ready on public.online_matches;
create trigger require_all_online_players_ready
    before update of status on public.online_matches
    for each row execute function public.require_all_online_players_ready();

